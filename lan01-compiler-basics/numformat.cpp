//format number with two decimal places
#include <iostream>

int main() {
    std::cout  << "The number to format is: " << "10.15" << "\n";
    float myNum= 10.15;
    double secNum = 10.20;
    std::cout << "The formatted number is: " << myNum << "\n";
    std::cout << "The second double number is: " << secNum << "\n";
    return 0;
}
  
